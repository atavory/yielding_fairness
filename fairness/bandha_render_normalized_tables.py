"""Render manuscript tables from the frozen normalized-price held-out summaries."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import statistics
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    summary_path = args.results / "source_sensitivity.json"
    comparison_path = args.results / "heldout_comparison.csv"
    summaries = json.loads(summary_path.read_text())
    index = {
        (r["currency"], r["capture_floor"], r["scope"], r["aggregation"]): r
        for r in summaries
        if r["comparator"] == "lift"
    }
    header = "% Generated by bandha_render_normalized_tables.py; post-review normalized bank.\n"
    table = (
        header
        + "\\begin{tabular}{rrrrr}\n\\toprule\nFloor & Seven mean & $p$ & Ten mean & $p$ \\\\\n\\midrule\n"
    )
    for floor in (0.90, 0.95, 0.98, 1.00):
        seven, all_sources = (
            index[("value", floor, scope, "median")] for scope in ("seven", "all")
        )
        table += f"{floor:.2f} & {seven['source_mean']:+.4f} & {seven['t_two_sided_p']:.4f} & {all_sources['source_mean']:+.4f} & {all_sources['t_two_sided_p']:.4f} \\\\\n"
    table += "\\bottomrule\n\\end{tabular}\n"
    (args.output / "bandha_normalized_headline_table.tex").write_text(table)
    rows = [
        r
        for r in csv.DictReader(comparison_path.open())
        if r["currency"] == "value" and float(r["capture_floor"]) == 0.95
    ]
    names = {
        "Australian MTPL": "Australian MTPL",
        "Belgian MTPL": "Belgian MTPL",
        "CMS provider fraud": "CMS provider fraud",
        "EU health insurance": "EU health",
        "French portfolio": "French portfolio",
        "Swedish motorcycle": "Swedish motorcycle",
    }
    table = (
        header
        + "\\begin{tabular}{lrrr}\n\\toprule\nSource & Group gap & LP gap & Lift \\\\\n\\midrule\n"
    )
    for source in sorted({r["source"] for r in rows}):
        subset = [r for r in rows if r["source"] == source]
        group, lp, lift = (
            statistics.median(float(r[k]) for r in subset)
            for k in ("group_test_gap", "lp_test_gap", "lift_vs_lp")
        )
        table += (
            f"{names.get(source, source)} & {group:.4f} & {lp:.4f} & {lift:+.4f} \\\\\n"
        )
    table += "\\bottomrule\n\\end{tabular}\n"
    (args.output / "bandha_normalized_lp_table.tex").write_text(table)
    table = (
        header
        + "\\begin{tabular}{llrrrr}\n\\toprule\nUnit & Floor & Seven medians & Seven means & Ten medians & Ten means \\\\\n\\midrule\n"
    )
    for currency in ("value", "count", "loss"):
        for floor in (0.90, 0.95, 0.98, 1.00):
            values = [
                index[(currency, floor, scope, aggregation)]["source_mean"]
                for scope in ("seven", "all")
                for aggregation in ("median", "mean")
            ]
            table += (
                f"{currency.capitalize()} & {floor:.2f} & "
                + " & ".join(f"{v:+.4f}" for v in values)
                + " \\\\\n"
            )
    table += "\\bottomrule\n\\end{tabular}\n"
    (args.output / "bandha_normalized_currency_table.tex").write_text(table)
    provenance = {
        "inputs": {
            str(p): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (summary_path, comparison_path)
        },
        "outputs": {
            p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in args.output.glob("bandha_normalized_*.tex")
        },
    }
    (args.output / "bandha_normalized_tables_provenance.json").write_text(
        json.dumps(provenance, indent=2)
    )


if __name__ == "__main__":
    main()
